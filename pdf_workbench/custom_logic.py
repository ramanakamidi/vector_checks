def build_analysis_images(rec: dict, mode: str):
    """The image(s) sent to the LLM for this object. The Q&A step reuses this, so
    analysis and Q&A always see the same pictures.
      crop         -> the caption-aware crop
      page         -> crop + full page
      page_context -> crop + previous / current / next page
                      (a merged multi-page table -> the crop of every part)"""
    if mode == 'crop':
        return rec['image_path']
    parts = rec.get('parts') or []
    if mode == 'page_context' and len(parts) > 1:
        return [(f"PART {i} of {len(parts)} (page {p['page_no']}) — crop of the SAME table:", p['image_path']) for i, p in enumerate(parts, start=1)]
    images = [('IMAGE 1 — CROP of the TARGET object (analyze this):', rec['image_path'])]
    if mode == 'page':
        if rec.get('page_image_path'):
            images.append(('IMAGE 2 — FULL PAGE (context only):', rec['page_image_path']))
        return images
    if rec.get('previous_page_image_path'):
        images.append(('PREVIOUS page (context only):', rec['previous_page_image_path']))
    if rec.get('page_image_path'):
        images.append(('CURRENT page (context only — the target is on this page):', rec['page_image_path']))
    if rec.get('next_page_image_path'):
        images.append(('NEXT page (context only):', rec['next_page_image_path']))
    return images

