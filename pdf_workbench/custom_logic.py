def parse_selection(raw: str, n: int) -> list:
    """'1', '1+2', '1,3', '2-4', 'all' -> sorted-unique 1-based indices."""
    raw = raw.strip().lower()
    if raw in ('all', '*'):
        return list(range(1, n + 1))
    indices = []
    for token in re.split('[+,\\s]+', raw):
        if not token:
            continue
        m = re.fullmatch('(\\d+)-(\\d+)', token)
        if m:
            indices.extend(range(int(m.group(1)), int(m.group(2)) + 1))
        else:
            indices.append(int(token))
    indices = list(dict.fromkeys(indices))
    if not indices or any((i < 1 or i > n for i in indices)):
        raise ValueError('selection out of range')
    return indices

