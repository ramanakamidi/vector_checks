def _normalize_category(category: str, object_type: str | None = None) -> str:
    normalized = re.sub('[\\s-]+', '_', str(category).strip().lower())
    aliases = {'value': 'value_lookup', 'label': 'label_identification', 'object': 'object_identification', 'description': 'content_description', 'text': 'text_retrieval', 'location': 'spatial_location'}
