def process_pdf_files(
    pdf_paths,
    output_dir: str,
    mode: str = "crop",
    progress_callback=None,
    text_documents: list[dict[str, Any]] | None = None,
    object_types: list[str] | set[str] | None = None,
):
    """Extract and analyze objects from PDF paths; returns raw and kept objects."""
    if mode not in {"crop", "page", "page_context"}:
        raise ValueError("mode must be crop, page, or page_context")
    selected_types = set(
        {"table", "image", "graph"} if object_types is None else object_types
    )
    supported_types = {"table", "image", "graph", "text"}
    unsupported_types = selected_types - supported_types
    if unsupported_types:
        raise ValueError(f"Unsupported object type(s): {', '.join(sorted(unsupported_types))}.")
    selected_object_types = selected_types - {"text"}
    if client is None or MODEL_NAME is None:
        raise RuntimeError("Configure Azure OpenAI credentials before analysis.")
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    raw_objects = []
    for index, pdf_path in enumerate(pdf_paths):
        _report_progress(progress_callback, f"Extracting {Path(pdf_path).name}", index / max(len(pdf_paths) * 2, 1))
        raw_objects.extend(
            extract_objects_from_pdf(
                str(pdf_path),
                str(output_path),
                index,
                mode,
                text_documents,
                selected_object_types,
            )
        )
    missing_crops = [part["image_path"] for record in raw_objects for part in record["parts"] if not Path(part["image_path"]).exists()]
    if missing_crops:
        raise RuntimeError("Some object crops were not saved: " + ", ".join(missing_crops))
    analyzed = []
    total = max(len(raw_objects), 1)
    for index, record in enumerate(raw_objects):
        _report_progress(progress_callback, f"Analyzing {record['doc_name']} page {record['page_no']}", 0.5 + 0.45 * index / total)
        result = analyze_object(record, mode)
        if result["classification"] == "skip" or result["classification"] not in selected_object_types:
            continue
        record["object_type"] = result["classification"]
        record["analysis_mode"] = mode
        record["characteristics"] = result["characteristics"]
        analyzed.append(record)
    if mode == "page_context":
        analyzed = merge_continued_tables(analyzed)
    analyzed.sort(key=lambda record: (record["_doc_idx"], record["page_no"], record["_top"]))
    sequence_numbers = defaultdict(int)
    for record in analyzed:
        key = (record["_doc_idx"], record["object_type"])
        sequence_numbers[key] += 1
        sequence = sequence_numbers[key]
        record["object_no"] = f"{record['object_type']} {sequence}"
        record["object_id"] = f"doc-{record['_doc_idx'] + 1}:page-{record['page_no']}:{record['object_type']}-{sequence}"
        if record["object_type"] == "table":
            record["table_no"] = sequence
        for part_index, part in enumerate(record["parts"], start=1):
            old_path = Path(part["image_path"])
            suffix = "" if part_index == 1 else f"_part{part_index}"
            new_path = old_path.parent / f"{record['doc_stem']}_page{part['page_no']}_{record['object_type']}{sequence}{suffix}.png"
            if old_path != new_path:
                old_path.rename(new_path)
            part["image_path"] = str(new_path)
        record["image_path"] = record["parts"][0]["image_path"]
    _report_progress(progress_callback, f"Analysis complete: {len(analyzed)} objects", 1.0)
    return raw_objects, analyzed


