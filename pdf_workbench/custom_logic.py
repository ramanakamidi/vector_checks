def _unmask(text, masks):
    for token, original in masks['pdf'].items():
        text = text.replace(token, original)
    for token, original in masks['q'].items():
        text = text.replace(token, f'"{original}"')
    return text

_PDF_QUOTED = re.compile(
    r"""(\bfrom\s+|\bpdf[\s_]*name\s+is\s+(?:not\s+)?)["“'‘]([^"”'’]+?\.pdf)["”'’]"""
)
