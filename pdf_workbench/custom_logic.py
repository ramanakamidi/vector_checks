def _verify_table_counts(
    result: dict,
    images,
    max_tokens: int,
    source_object_type: str,
) -> dict:
    """Re-checks a table's row/column enumeration against the image(s) and
    corrects the counts. Falls back to the original result on any problem."""
    c = result['characteristics']
    previous = {'row_enumeration': c.get('row_enumeration') or [], 'column_enumeration': c.get('column_enumeration') or [], 'num_header_rows': c.get('num_header_rows'), 'num_header_columns': c.get('num_header_columns')}
    prompt = VERIFY_PROMPT + "\nThe first reader's lists:\n" + json.dumps(previous, ensure_ascii=False)
    parsed = _call_analysis_json(prompt, images, 1, max_tokens=max_tokens)
    verified_classification = str(parsed.get("classification") or "").strip().lower()
    if verified_classification in {"graph", "image", "skip"}:
        return _normalize_combined_response(parsed, source_object_type)
    if verified_classification != "table":
        return result
    rows = parsed.get('row_enumeration')
    if not isinstance(rows, list):
        return result
    rows = [str(x).strip() for x in rows if str(x).strip()]
    if not rows:
        return result
    cols = parsed.get('column_enumeration')
    cols = [str(x).strip() for x in cols if str(x).strip()] if isinstance(cols, list) else []
    if not cols:
        cols = [str(x) for x in c.get('column_enumeration') or []]
    old_rows, old_cols = (c.get('num_rows'), c.get('num_columns'))
    n_rows = len(rows)
    n_cols = len(cols) if cols else old_cols
    h_rows = _nonnegative_int(parsed.get('num_header_rows'))
    h_cols = _nonnegative_int(parsed.get('num_header_columns'))
    h_rows = c.get('num_header_rows') if h_rows is None else h_rows
    h_cols = c.get('num_header_columns') if h_cols is None else h_cols
    c['row_enumeration'], c['column_enumeration'] = (rows, cols)
    c['num_rows'], c['num_columns'] = (n_rows, n_cols)
    if h_rows is not None:
        c['num_header_rows'] = min(h_rows, n_rows)
        c['num_data_rows'] = n_rows - c['num_header_rows']
    if h_cols is not None and n_cols is not None:
        c['num_header_columns'] = min(h_cols, n_cols)
        c['num_data_columns'] = n_cols - c['num_header_columns']
    if (old_rows, old_cols) != (n_rows, n_cols):
        note = f'counts corrected by verification: rows {old_rows} -> {n_rows}, columns {old_cols} -> {n_cols}'
        c['notes'] = f"{c['notes']} | {note}" if c.get('notes') else note
        print(f'    verification: {note}')
    c = _normalize_table_counts(c)
    c['structure_source'] = 'llm_vision_verified'
    if c.get('analysis_status') != 'failed':
        c['analysis_status'] = 'needs_review' if c.get('structure_warning') else 'complete'
    result['characteristics'] = c
    return result

def _normalize_confidence(value) -> str:
    value = str(value or 'low').strip().lower()
    return value if value in {'high', 'medium', 'low'} else 'low'

def _nonnegative_int(value):
    if isinstance(value, bool):
        return None
    try:
        value = int(value)
        return value if value >= 0 else None
    except (TypeError, ValueError):
        return None

def _bool_or_none(value):
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        v = value.strip().lower()
        if v == 'true':
            return True
        if v == 'false':
            return False
    return None

def _normalize_table_counts(parsed: dict) -> dict:
    for field in ('num_rows', 'num_columns', 'num_header_rows', 'num_header_columns', 'num_data_rows', 'num_data_columns', 'num_merged_cells'):
        parsed[field] = _nonnegative_int(parsed.get(field))
    parsed['structure_source'] = 'llm_vision'
    warnings = []
    required_counts = ('num_rows', 'num_columns', 'num_header_rows', 'num_header_columns', 'num_data_rows', 'num_data_columns')
    missing_counts = [field for field in required_counts if parsed.get(field) is None]
    if missing_counts:
        warnings.append('missing counts: ' + ', '.join(missing_counts))
    for enum_key, count_key in (('row_enumeration', 'num_rows'), ('column_enumeration', 'num_columns')):
        enumeration = parsed.get(enum_key)
        if isinstance(enumeration, list) and enumeration and (parsed.get(count_key) is not None) and (len(enumeration) != parsed[count_key]):
            warnings.append(f'{enum_key} has {len(enumeration)} entries but {count_key} = {parsed[count_key]}')
    header_rows = parsed.get('num_header_rows')
    header_columns = parsed.get('num_header_columns')
    if header_rows is not None:
        parsed['has_column_header'] = header_rows > 0
        parsed['is_multi_level_header'] = header_rows > 1
    if header_columns is not None:
        parsed['has_row_header'] = header_columns > 0
    if header_rows is not None and header_columns is not None:
        if header_rows > 0 and header_columns > 0:
            parsed['header_type'] = 'both_row_and_column'
        elif header_rows > 0:
            parsed['header_type'] = 'column_only'
        elif header_columns > 0:
            parsed['header_type'] = 'row_only'
        else:
            parsed['header_type'] = 'none'
    if parsed.get('num_merged_cells') is not None:
        parsed['has_merged_cells'] = parsed['num_merged_cells'] > 0
    if None not in (parsed.get('num_rows'), parsed.get('num_header_rows'), parsed.get('num_data_rows')) and parsed['num_rows'] != parsed['num_header_rows'] + parsed['num_data_rows']:
        warnings.append(f"row arithmetic: {parsed['num_rows']} != {parsed['num_header_rows']} + {parsed['num_data_rows']}")
    if None not in (parsed.get('num_columns'), parsed.get('num_header_columns'), parsed.get('num_data_columns')) and parsed['num_columns'] != parsed['num_header_columns'] + parsed['num_data_columns']:
        warnings.append(f"column arithmetic: {parsed['num_columns']} != {parsed['num_header_columns']} + {parsed['num_data_columns']}")
    if warnings:
        parsed['structure_warning'] = '; '.join(warnings)
    else:
        parsed.pop('structure_warning', None)
    return parsed

def _caption_context(caption) -> str:
    if not caption:
        return '\nNo Docling-linked caption is available.'
    return f'\nDocling-linked caption metadata (context only; never return or rewrite it as an LLM-generated caption): {json.dumps(str(caption), ensure_ascii=False)}'

def _normalize_combined_response(parsed: dict, source_object_type: str) -> dict:
    classification = str(parsed.get('classification') or '').strip().lower()
    if classification not in {'table', 'graph', 'image', 'skip'}:
        if source_object_type == 'table':
            classification = 'table'
        elif source_object_type == 'picture':
            classification = 'image'
        else:
            classification = 'skip'
    result = {'classification': classification, 'classification_confidence': _normalize_confidence(parsed.get('classification_confidence')), 'classification_reason': parsed.get('classification_reason'), 'characteristics': {}}
    if classification == 'skip':
        return result
    raw_characteristics = parsed.get('characteristics')
    if not isinstance(raw_characteristics, dict):
        raw_characteristics = {}
    characteristics = {key: value for key, value in raw_characteristics.items() if key not in {'table', 'graph', 'image'}}
    type_characteristics = raw_characteristics.get(classification)
    if isinstance(type_characteristics, dict):
        characteristics.update(type_characteristics)
    if not characteristics:
        characteristics = {'description': 'ANALYSIS_FAILED', 'confidence': 'low', 'notes': 'ANALYSIS_FAILED'}
    characteristics['confidence'] = _normalize_confidence(characteristics.get('confidence'))
    if classification == 'table':
        characteristics = _normalize_table_counts(characteristics)
    elif classification == 'graph':
        characteristics['chart_type'] = _normalize_visual_type(characteristics.get('chart_type'), GRAPH_TYPES, {'column': 'bar', 'column_chart': 'bar', 'bar_chart': 'bar', 'grouped_bar_chart': 'grouped_bar', 'stacked_bar_chart': 'stacked_bar', 'horizontal_bar_chart': 'horizontal_bar', 'line_chart': 'line', 'pie_chart': 'pie', 'donut': 'doughnut', 'donut_chart': 'doughnut', 'scatter_plot': 'scatter', 'boxplot': 'box_plot', 'combined': 'combo', 'combination': 'combo'})
    else:
        characteristics['image_subtype'] = _normalize_visual_type(characteristics.get('image_subtype'), IMAGE_TYPES, {'flowchart': 'flow_diagram', 'flow_chart': 'flow_diagram', 'workflow': 'flow_diagram', 'process_flow': 'process_diagram', 'architecture': 'architecture_diagram', 'block': 'block_diagram', 'network': 'network_diagram', 'org_chart': 'organizational_chart', 'organization_chart': 'organizational_chart', 'scan': 'document_scan', 'document_page': 'document_screenshot', 'multi_panel': 'composite_figure'})
        characteristics['people_count'] = _nonnegative_int(characteristics.get('people_count'))
    characteristics['classification_confidence'] = result['classification_confidence']
    characteristics['classification_reason'] = result['classification_reason']
