def _mask_query(q):
    masks = {'pdf': {}, 'q': {}}

    def pdf_repl(m):
        token = f"pdfname{len(masks['pdf'])}x"
        masks['pdf'][token] = m.group(2).strip()
        return f'{m.group(1)}{token}'

    def q_repl(m):
        token = f"qstr{len(masks['q'])}x"
        masks['q'][token] = m.group(1).strip()
        return token
    q = _PDF_QUOTED.sub(pdf_repl, q)
    q = _PDF_PLAIN.sub(pdf_repl, q)
    q = re.sub('[\\"“]([^\\"”]+)[\\"”]', q_repl, q)
    q = re.sub("(?<!\\w)'([^']+)'(?!\\w)", q_repl, q)
    return (q, masks)

def _parse_emptiness(clause):
    fw = '(title|caption|description)'

    def field_of(word):
        return 'description' if word == 'description' else 'title'
    m = re.search(f'\\b{fw}\\s+(?:is\\s+)?not\\s+(?:empty|missing|blank|set|none|null)\\b', clause)
    if m:
        return {'field': field_of(m.group(1)), 'operator': 'notempty', 'value': None}
    m = re.search(f'\\b(?:no|without|missing|empty)\\s+(?:an?\\s+)?{fw}\\b', clause)
    if m:
        return {'field': field_of(m.group(1)), 'operator': 'empty', 'value': None}
    m = re.search(f'\\b{fw}\\s+(?:is\\s+|are\\s+)?(?:empty|missing|blank|none|null)\\b', clause)
    if m:
        return {'field': field_of(m.group(1)), 'operator': 'empty', 'value': None}
    m = re.fullmatch(f'(?:(?:has|have|with|having)\\s+)?(?:an?\\s+)?{fw}', clause)
    if m:
        return {'field': field_of(m.group(1)), 'operator': 'notempty', 'value': None}
    return None

def _parse_continuation(clause):
    value = not _NEG_RE.search(clause)
    if re.search('\\bcontinu\\w*\\s+(?:from|of)?\\s*(?:the\\s+)?(?:previous|prior|last)\\s+page', clause):
        return {'field': 'continues_from_previous_page', 'operator': '==', 'value': value}
    if re.search('\\bcontinu\\w*\\s+(?:on|onto|to)?\\s*(?:the\\s+)?next\\s+page', clause):
        return {'field': 'continues_on_next_page', 'operator': '==', 'value': value}
    if re.search('\\b(?:spans?|spanning|split)\\s+(?:across\\s+|over\\s+)?(?:multiple\\s+|several\\s+|two\\s+)?pages?\\b|\\bmulti[\\s-]?page\\b|\\bcontinued\\b', clause):
        return {'field': 'spans_pages', 'operator': '==', 'value': value}
    return None

def _finalize_text_condition(field, op, value):
    value = value.strip(' "\'')
    if field == 'object_type':
        value = _canon_type(value) or value
    elif field == 'chart_type':
        value = _chart_kind_in(value) or re.sub('[\\s-]+', '_', value)
    elif field == 'image_subtype':
        value = re.sub('[\\s-]+', '_', value)
    if field in _LENIENT_TEXT_FIELDS:
        if op == '==':
            op = 'contains'
        elif op == '!=':
            op = '!contains'
    return {'field': field, 'operator': op, 'value': value}

def _parse_text_condition(clause, masks):
    for phrase, field in TEXT_FIELD_PHRASES:
        pattern = '\\b' + re.escape(phrase).replace('\\ ', '[\\s_]*') + '\\b'
        m = re.search(pattern, clause)
        if not m:
            continue
        tail = clause[m.end():].strip()
        for op_pattern, op in TEXT_OPERATORS:
            om = re.match(op_pattern, tail)
            if om:
                value = _resolve_value(om.group(1), masks)
                if value:
                    return _finalize_text_condition(field, op, value)
    return None

def _parse_boolean_condition(clause):
    has_digit = bool(re.search('\\d', clause))
    for pattern, field, only_without_digit in BOOLEAN_PHRASES:
        if only_without_digit and has_digit:
            continue
        if re.search(f'(?<![\\w]){pattern}(?![\\w])', clause):
            return {'field': field, 'operator': '==', 'value': not _NEG_RE.search(clause)}
    return None

def _parse_chart_kind_condition(clause):
    kind = _chart_kind_in(clause)
    if not kind:
        return None
    if not re.search('\\b(?:charts?|graphs?|plots?)\\b', clause):
        core = re.sub('\\b(?:has|have|with|without|no|not|an?|the|having|only|show|all)\\b', ' ', clause)
        core = re.sub('\\s+', ' ', core).strip()
        if core not in _CHART_ALIAS_TEXTS and core.rstrip('s') not in _CHART_ALIAS_TEXTS:
            return None
    operator = '!contains' if _NEG_RE.search(clause) else 'contains'
    return {'field': 'chart_type', 'operator': operator, 'value': kind}

def _parse_type_is_condition(clause):
    m = re.search(f'\\b(?:is|are)\\s+(not\\s+)?(?:an?\\s+)?({_TYPE_WORD})\\b', clause)
    if m:
        return {'field': 'object_type', 'operator': '!=' if m.group(1) else '==', 'value': _canon_type(m.group(2))}
    m = re.search(f"\\b(?:isn'?t|not|except|excluding|exclude|without|no)\\s+(?:an?\\s+)?({_TYPE_WORD})\\b", clause)
    if m:
        return {'field': 'object_type', 'operator': '!=', 'value': _canon_type(m.group(1))}
    return None

def _parse_numeric_condition(clause):
    field = None
    for pattern, candidate in NUMERIC_FIELD_PATTERNS:
        if re.search(f'(?<![\\w])(?:{pattern})(?![\\w])', clause):
            field = candidate
            break
    if field is None:
        return None
    for op, rx in _NUMERIC_OPERATOR_PATTERNS:
        m = rx.search(clause)
        if not m:
            continue
        if op == 'between':
            lo, hi = (_to_number(m.group(1)), _to_number(m.group(2)))
            if lo > hi:
                lo, hi = (hi, lo)
            return {'field': field, 'operator': 'between', 'value': [lo, hi]}
        return {'field': field, 'operator': op, 'value': _to_number(m.group(1))}
    m = re.search(f'(?<![\\w.]){_NUM}(?![\\w.])', clause)
    if m:
        return {'field': field, 'operator': '==', 'value': _to_number(m.group(1))}
    return None

def parse_single(clause, masks):
    """Parse ONE atomic condition. Returns a condition dict or None."""
    m = re.fullmatch(f'(?:the\\s+)?({_TYPE_WORD})\\s*(?:no\\.?|number|num|#)?\\s*(\\d+)', clause)
    if m:
        return {'field': 'object_no', 'operator': '==', 'value': f'{_canon_type(m.group(1))} {int(m.group(2))}'}
    m = re.fullmatch(f'(?:(?:all|only|the)\\s+)*({_TYPE_WORD})', clause)
    if m:
        return {'field': 'object_type', 'operator': '==', 'value': _canon_type(m.group(1))}
    for parser in (_parse_emptiness, _parse_continuation):
        cond = parser(clause)
        if cond:
            return cond
    cond = _parse_text_condition(clause, masks)
    if cond:
        return cond
    for parser in (_parse_boolean_condition, _parse_chart_kind_condition, _parse_type_is_condition, _parse_numeric_condition):
        cond = parser(clause)
        if cond:
            return cond
    return None

_TYPE_PREFIX = re.compile(
    rf"^(?:all\s+)?({_TYPE_WORD})\s+(?:with|having|containing|where|whose|"
    r"that\s+(?:have|has|are|is)|which\s+(?:have|has|are|is))\s+(.+)$"
)
def parse_atomic(clause, masks):
    """A condition, optionally prefixed by a type: 'tables with more than 5 rows'."""
    m = _TYPE_PREFIX.match(clause)
    if m:
        rest = parse_atomic(m.group(2).strip(), masks)
        if rest is not None:
            return [{'field': 'object_type', 'operator': '==', 'value': _canon_type(m.group(1))}] + rest
    single = parse_single(clause, masks)
    return [single] if single else None

_PDF_COND_FROM = re.compile(r"(?:\b(not)\s+)?\bfrom\s+(pdfname\d+x)")
_PDF_COND_NAME = re.compile(r"\bpdf[\s_]*name\s+is\s+(?:(not)\s+)?(pdfname\d+x)")
def _clean_clause(text):
    text = re.sub('\\s+', ' ', text).strip(' ,.;')
    text = re.sub('^(?:and|also|then)\\s+', '', text)
    return text.strip()

def parse_clause(clause, masks):
    """One and/or-free part of the query -> list of conditions (all ANDed)."""
    clause = _clean_clause(clause)
    if not clause:
        return None
    conditions = []

    def grab(m):
        conditions.append({'field': 'doc_name', 'operator': '!=' if m.group(1) else '==', 'value': masks['pdf'][m.group(2)]})
        return ' '
    rest = _PDF_COND_FROM.sub(grab, clause)
    rest = _PDF_COND_NAME.sub(grab, rest)
    rest = _clean_clause(rest)
    for _ in range(3):
        rest = _clean_clause(re.sub('^(?:in|of|the|all|only|with|where|that|are)\\b\\s*|\\s*\\b(?:in|of|the|with|where|that|are)$', '', rest))
    if not rest:
        return conditions or None
    sub = parse_atomic(rest, masks)
    if sub is None:
        return None
    return conditions + sub

def parse_query(query: str):
    """
    Returns {"groups": [[cond, cond], [cond]]}  ==  (c AND c) OR (c).
    AND binds tighter than OR. If any part is not understood, nothing is
    returned (so a typo can never silently widen the result set).
    """
    q = re.sub('\\s+', ' ', str(query).strip().lower())
    q = re.sub('^(?:please\\s+)?(?:show|find|list|get|display|select|filter|give)\\s+(?:me\\s+)?(?:all\\s+)?(?:the\\s+)?', '', q)
    q = q.strip(' .;')
    if not q:
        return None
    q, masks = _mask_query(q)
    q = re.sub(f'\\bbetween\\s+{_NUM}\\s+and\\s+{_NUM}', 'between \\1 to \\2', q)
    groups, bad_parts = ([], [])
    for or_part in re.split('\\bor\\b', q):
        group = []
        for part in re.split('\\band\\b', or_part):
            if not part.strip(' ,.;'):
                continue
            conditions = parse_clause(part, masks)
            if conditions is None:
                bad_parts.append(_unmask(part.strip(), masks))
            else:
                group.extend(conditions)
        if group:
            groups.append(group)
    if bad_parts:
        print("Couldn't understand: " + '; '.join((f"'{p}'" for p in bad_parts)))
        return None
    return {'groups': groups} if groups else None

def describe_filter(structured_filter: dict) -> str:

    def cond_text(c):
        if c['operator'] in ('empty', 'notempty'):
            return f"{c['field']} is {('empty' if c['operator'] == 'empty' else 'not empty')}"
        return f"{c['field']} {c['operator']} {c['value']!r}"
    return ' OR '.join(('(' + ' AND '.join((cond_text(c) for c in group)) + ')' for group in structured_filter['groups']))

def _is_empty(value) -> bool:
    return value is None or (isinstance(value, str) and (not value.strip())) or (isinstance(value, (list, tuple, set, dict)) and len(value) == 0)

def get_field_value(record: dict, field: str):
    c = record.get('characteristics') or {}
    if field == 'title':
        return record.get('docling_title')
    if field == 'description':
        parts = [str(x).strip() for x in (c.get('content_summary'), c.get('description')) if x and str(x).strip()]
        return ' '.join(parts) if parts else None
    if field == 'spans_pages':
        if len(record.get('pages') or []) > 1:
            return True
        flags = [c.get('continues_from_previous_page'), c.get('continues_on_next_page')]
        if any((f is True for f in flags)):
            return True
        if all((f is False for f in flags)):
            return False
        return None
    if field in record:
        return record[field]
    return c.get(field)

def check_condition(field_value, operator: str, target_value) -> bool:
    if operator == 'empty':
        return _is_empty(field_value)
    if operator == 'notempty':
        return not _is_empty(field_value)
    if field_value is None:
        return False
    if isinstance(field_value, (list, tuple)):
        field_value = ', '.join((str(v) for v in field_value))
    try:
        if operator in ('==', '!='):
            if isinstance(field_value, bool) or isinstance(target_value, bool):
                equal = field_value == target_value
            elif isinstance(field_value, (int, float)) and isinstance(target_value, (int, float)):
                equal = float(field_value) == float(target_value)
            else:
                equal = str(field_value).strip().lower() == str(target_value).strip().lower()
            return equal if operator == '==' else not equal
        if operator == '>':
            return float(field_value) > float(target_value)
        if operator == '<':
            return float(field_value) < float(target_value)
        if operator == '>=':
            return float(field_value) >= float(target_value)
        if operator == '<=':
            return float(field_value) <= float(target_value)
        if operator == 'between':
            lo, hi = target_value
            return float(lo) <= float(field_value) <= float(hi)
        if operator == 'contains':
            return str(target_value).lower() in str(field_value).lower()
        if operator == '!contains':
            return str(target_value).lower() not in str(field_value).lower()
    except (ValueError, TypeError):
        return False
    return False

def _condition_matches(record: dict, c: dict) -> bool:
    if c['field'] == 'page_no' and len(record.get('pages') or []) > 1:
        return any((check_condition(p, c['operator'], c['value']) for p in record['pages']))
    return check_condition(get_field_value(record, c['field']), c['operator'], c['value'])

def apply_filter(records: list, structured_filter: dict) -> list:
    groups = structured_filter.get('groups', [])
    matches = []
    for record in records:
        for group in groups:
            if all((_condition_matches(record, c) for c in group)):
                matches.append(record)
                break
    return matches

