def bbox_to_pixels(bbox, page_width_pts, page_height_pts, img_width, img_height):
    scale_x = img_width / page_width_pts
    scale_y = img_height / page_height_pts
    l, t, r, b = (bbox.l, bbox.t, bbox.r, bbox.b)
    if bbox.coord_origin.name == 'BOTTOMLEFT':
        top = page_height_pts - t
        bottom = page_height_pts - b
    else:
        top, bottom = (t, b)
    left_px = l * scale_x
    right_px = r * scale_x
    top_px = top * scale_y
    bottom_px = bottom * scale_y
    if bottom_px < top_px:
        top_px, bottom_px = (bottom_px, top_px)
    return (left_px, top_px, right_px, bottom_px)

def get_object_caption(doc, obj):
    """
    Pulls the EXACT caption/title text Docling linked to this object
    (tables or pictures). Wrapped defensively so a mismatch won't crash.
    """
    try:
        caption_refs = getattr(obj, 'captions', None) or []
        texts = []
        for ref in caption_refs:
            try:
                resolved = ref.resolve(doc) if hasattr(ref, 'resolve') else None
                text = getattr(resolved, 'text', None) if resolved else None
                if text:
                    texts.append(text.strip())
            except Exception:
                continue
        joined = ' '.join(texts).strip()
        if joined:
            return joined
        caption_text = getattr(obj, 'caption_text', None)
        if callable(caption_text):
            try:
                return (caption_text(doc) or '').strip() or None
            except Exception:
                return None
        return None
    except Exception:
        return None

MIN_PAD_X_PX = 16
MIN_PAD_Y_PX = 24
CAPTION_PAD_X_RATIO = 0.03
CAPTION_PAD_Y_RATIO = 0.04
CAPTION_PAD_Y_PAGE_FRACTION = 0.025
FALLBACK_PAD_X_RATIO = 0.08
FALLBACK_PAD_Y_RATIO = 0.10
FALLBACK_PAD_Y_PAGE_FRACTION = 0.06
MAX_CAPTION_UNION_GROWTH = 4.0
def get_caption_boxes(doc, obj, page_no: int) -> list:
    """Bounding boxes of the caption text items Docling linked to `obj`,
    restricted to the given page."""
    boxes = []
    for ref in getattr(obj, 'captions', None) or []:
        try:
            resolved = ref.resolve(doc) if hasattr(ref, 'resolve') else None
            for prov in getattr(resolved, 'prov', None) or []:
                if prov.page_no == page_no:
                    boxes.append(prov.bbox)
        except Exception:
            continue
    return boxes

def describe_position(l, t, r, b, img_w, img_h) -> str:
    """Rough location of an object on its page, e.g. 'top', 'middle-left', 'bottom-right'."""
    cx = (l + r) / 2 / img_w
    cy = (t + b) / 2 / img_h
    vertical = 'top' if cy < 1 / 3 else 'bottom' if cy > 2 / 3 else 'middle'
    if (r - l) / img_w > 0.7:
        return vertical
    horizontal = 'left' if cx < 1 / 3 else 'right' if cx > 2 / 3 else 'center'
    if vertical == 'middle' and horizontal == 'center':
        return 'center'
    return f'{vertical}-{horizontal}'

def crop_object_to_image(doc, obj, prov, img_filename, out_dir):
    """Crops one object (table/picture) from its page -> PNG, caption-aware.
    Returns a dict (path, page_no, top, size, caption_in_crop, position) or
    None when the page image is unavailable."""
    page_no = prov.page_no
    page = doc.pages.get(page_no)
    if page is None or page.image is None:
        return None
    page_image = page.image.pil_image
    page_width_pts, page_height_pts = (page.size.width, page.size.height)
    img_width, img_height = page_image.size
    l, t, r, b = bbox_to_pixels(prov.bbox, page_width_pts, page_height_pts, img_width, img_height)
    caption_boxes = [bbox_to_pixels(cb, page_width_pts, page_height_pts, img_width, img_height) for cb in get_caption_boxes(doc, obj, page_no)]
    left, top, right, bottom = (l, t, r, b)
    caption_in_crop = False
    if caption_boxes:
        left = min([l] + [c[0] for c in caption_boxes])
        top = min([t] + [c[1] for c in caption_boxes])
        right = max([r] + [c[2] for c in caption_boxes])
        bottom = max([b] + [c[3] for c in caption_boxes])
        object_area = max(1.0, (r - l) * (b - t))
        if (right - left) * (bottom - top) <= MAX_CAPTION_UNION_GROWTH * object_area:
            caption_in_crop = True
        else:
            left, top, right, bottom = (l, t, r, b)
    if caption_in_crop:
        x_ratio, y_ratio, y_page = (CAPTION_PAD_X_RATIO, CAPTION_PAD_Y_RATIO, CAPTION_PAD_Y_PAGE_FRACTION)
    else:
        x_ratio, y_ratio, y_page = (FALLBACK_PAD_X_RATIO, FALLBACK_PAD_Y_RATIO, FALLBACK_PAD_Y_PAGE_FRACTION)
    pad_x = max(MIN_PAD_X_PX, int((right - left) * x_ratio))
    pad_y = max(MIN_PAD_Y_PX, int((bottom - top) * y_ratio), int(img_height * y_page))
    crop_box = (max(0, int(left) - pad_x), max(0, int(top) - pad_y), min(img_width, int(right) + pad_x), min(img_height, int(bottom) + pad_y))
    cropped = page_image.crop(crop_box)
    img_path = Path(out_dir) / img_filename
    cropped.save(img_path)
    return {'path': img_path, 'page_no': page_no, 'top': t, 'width': cropped.width, 'height': cropped.height, 'caption_in_crop': caption_in_crop, 'position': describe_position(l, t, r, b, img_width, img_height)}

def save_page_image(doc, page_no: int, doc_stem: str, out_dir, max_side: int=PAGE_MAX_SIDE):
    """Saves one full page as PNG (downscaled if very large).
    Returns (path, width, height) or (None, None, None) if the page has no image."""
    page = doc.pages.get(page_no)
    if page is None or page.image is None:
        return (None, None, None)
    path = Path(out_dir) / f'{doc_stem}_page{page_no}_full.png'
    img = page.image.pil_image
    if max(img.size) > max_side:
        img = img.copy()
        img.thumbnail((max_side, max_side))
    img.save(path)
    return (path, img.width, img.height)

def extract_objects_from_pdf(
    pdf_path: str,
    output_dir: str = "output",
    doc_idx: int = 0,
    mode: str = "crop",
    text_documents: list[dict[str, Any]] | None = None,
    object_types: set[str] | None = None,
) -> list:
    """
    Runs Docling on ONE PDF and returns one record per detected table / picture.

    Every mode gets a caption-aware crop of each object.
      mode "crop"         : crop only
      mode "page"         : + the full page the object is on
      mode "page_context" : + the previous and next page images; a table that
                            Docling reports on several pages gets one crop per
                            page part (they are merged into one object later)

    Docling contributes only crops, captions, page metadata and a weak
    table/picture label. Stage 2 (the LLM) gives the final classification.
    """
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    doc_stem = Path(pdf_path).stem
    doc_name = Path(pdf_path).name
    converter = get_converter()
    doc = converter.convert(pdf_path).document
    if text_documents is not None:
        try:
            markdown = doc.export_to_markdown()
            if not isinstance(markdown, str):
                raise TypeError("Docling Markdown export did not return text.")
            page_markdowns = [
                {
                    "page_no": int(page_no),
                    "markdown": doc.export_to_markdown(page_no=page_no),
                }
                for page_no in sorted(doc.pages)
            ]
            text_documents.append({
                "document_id": f"doc-{doc_idx + 1}",
                "pdf_name": doc_name,
                "markdown": markdown,
                "page_markdowns": page_markdowns,
            })
        except Exception as exc:
            text_documents.append({
                "document_id": f"doc-{doc_idx + 1}",
                "pdf_name": doc_name,
                "error": f"{type(exc).__name__}: {exc}",
            })
    page_cache = {}
    source_types = (
        {"table", "image", "graph"}
        if object_types is None
        else set(object_types)
    )

    def get_page(n):
        if n not in page_cache:
            page_cache[n] = save_page_image(doc, n, doc_stem, out_dir)
        return page_cache[n]
    records = []
    raw_counter = 0
    for kind, items in (('table', doc.tables), ('picture', doc.pictures)):
        if kind == "table" and "table" not in source_types:
            continue
        if kind == "picture" and not source_types.intersection({"image", "graph"}):
            continue
        for item_no, obj in enumerate(items):
            if not obj.prov:
                continue
            raw_counter += 1
            provs, seen_pages = ([], set())
            for prov in obj.prov:
                if prov.page_no not in seen_pages:
                    seen_pages.add(prov.page_no)
                    provs.append(prov)
            if not (kind == 'table' and mode == 'page_context'):
                provs = provs[:1]
            parts = []
            for k, prov in enumerate(provs, start=1):
                suffix = '' if k == 1 else f'_part{k}'
                crop = crop_object_to_image(doc, obj, prov, f'{doc_stem}_page{prov.page_no}_raw{raw_counter}{suffix}.png', out_dir)
                if crop is None:
                    print(f'[{doc_name}] {kind} {item_no}: crop failed for page {prov.page_no}.')
                    continue
                parts.append(crop)
            if not parts:
                print(f'[{doc_name}] {kind} {item_no}: no usable crop, skipped.')
                continue
            first = parts[0]
            rec = {'doc_name': doc_name, 'doc_stem': doc_stem, '_doc_idx': doc_idx, 'page_no': first['page_no'], 'pages': [p['page_no'] for p in parts], '_top': first['top'], 'source_object_type': kind, 'image_path': str(first['path']), 'docling_title': get_object_caption(doc, obj), 'image_width': first['width'], 'image_height': first['height'], 'position': first['position'], 'caption_in_crop': first['caption_in_crop'], 'parts': [{'page_no': p['page_no'], 'image_path': str(p['path']), 'width': p['width'], 'height': p['height']} for p in parts]}
            if kind == "table":
                table_markdown = obj.export_to_markdown(doc=doc)
                if not isinstance(table_markdown, str):
                    raise TypeError("Docling table Markdown export did not return text.")
                rec["table_markdown"] = table_markdown.strip()
            if mode in ('page', 'page_context'):
                page_path, _, _ = get_page(first['page_no'])
                rec['page_image_path'] = str(page_path) if page_path else None
            if mode == 'page_context':
                prev_path, _, _ = get_page(first['page_no'] - 1)
                next_path, _, _ = get_page(first['page_no'] + 1)
                rec['previous_page_image_path'] = str(prev_path) if prev_path else None
                rec['next_page_image_path'] = str(next_path) if next_path else None
            records.append(rec)
            span = f" (pages {rec['pages']})" if len(parts) > 1 else ''
            print(f"[{doc_name}] {kind} {item_no} on page {first['page_no']}{span} -> {first['path']} (caption in crop: {first['caption_in_crop']})")
    return records

