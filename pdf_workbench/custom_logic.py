def _parse_qa_with_category(raw_text: str, object_type: str) -> dict:
    """
    Parse and validate JSON Q&A output. Invalid categories, empty fields, and
    duplicate questions are rejected instead of being written to Excel.
    """
    result = {'characteristics': None, 'pairs': []}
    cleaned = re.sub('^```(?:json)?\\s*|\\s*```$', '', raw_text.strip(), flags=re.MULTILINE).strip()
    try:
        payload = json.loads(cleaned)
    except (json.JSONDecodeError, TypeError):
        return result
    pairs = payload.get('pairs', []) if isinstance(payload, dict) else []
    if not isinstance(pairs, list):
        return result
    allowed_categories = set(CATEGORY_DEFINITIONS.get(object_type, CATEGORY_DEFINITIONS['table']))
    seen_questions = set()
    for pair in pairs:
        if not isinstance(pair, dict):
            continue
        question = str(pair.get('question') or '').strip()
        answer = str(pair.get('expected_answer') or '').strip()
        category = _normalize_category(pair.get('category') or '', object_type)
        question_key = re.sub('\\W+', ' ', question.lower()).strip()
        if not question or not answer or category not in allowed_categories:
            continue
        if question_key in seen_questions:
            continue
        seen_questions.add(question_key)
        result['pairs'].append({'question': question, 'category': category, 'expected_answer': answer})
    return result

def generate_qa_for_object(image_path, num_qa: int, object_type: str='table', description: str=None, target_context: str='') -> dict:
    """
    Generates natural end-user Q&A pairs and validates their categories.
    Object characteristics are produced once in Stage 2, not regenerated here.

    `image_path` may be a single path (crop mode / page mode) or a list of
    (label, path) tuples (page_context mode when the object spans pages).
    `target_context` (page modes only) tells the model WHICH object on the page
    to ask about, using the Stage 2 metadata.
    """
    type_label = QA_TYPE_LABELS.get(object_type, 'object')
    type_instruction = QA_TYPE_INSTRUCTIONS.get(object_type, QA_TYPE_INSTRUCTIONS['table'])
    title_context = f' titled "{description}"' if description else ''
    category_list = ', '.join(CATEGORY_DEFINITIONS.get(object_type, CATEGORY_DEFINITIONS['table']))
    prompt = QA_PROMPT_TEMPLATE.format(type_label=type_label, title_context=title_context, target_context=target_context, type_instruction=type_instruction.strip(), category_list=category_list, style_examples=QA_STYLE_EXAMPLES.get(object_type, '').strip(), n=num_qa)
    raw_text = call_openai_vision(prompt, image_path)
    parsed = _parse_qa_with_category(raw_text, object_type)
    if len(parsed['pairs']) != num_qa:
        print(f"  Model returned {len(parsed['pairs'])} pair(s) instead of {num_qa} — asking it to fix...")
        correction = (
            f"{target_context}\n"
            "Re-evaluate the previous response against the supplied image(s). "
            "Return ONLY valid JSON with a top-level 'pairs' array and no "
            f"more than {num_qa} distinct question-and-answer objects. Return "
            f"{num_qa} only if that many independently useful pairs are "
            "clearly supported by visible evidence; otherwise return fewer. "
            "Do not add a fact, value, unit, label, or relationship that is "
            "not legible or unambiguous in the target image(s). Remove or "
            "rewrite unsupported, duplicated, vague, or incorrectly answered "
            "pairs. Each pair must have non-empty 'question', 'category', "
            f"and 'expected_answer' strings; category must be one of: {category_list}. "
            "Questions must sound like natural end-user questions, and each "
            "answer must directly answer its question with only supported "
            f"detail. The previous response produced {len(parsed['pairs'])} "
            "valid pairs. Return fewer rather than guessing. Do not include "
            "commentary or markdown.\n\nPrevious response:\n"
            f"{raw_text}"
        )
        try:
            raw_text2 = call_openai_vision(correction, image_path)
            retry = _parse_qa_with_category(raw_text2, object_type)
            if min(len(retry['pairs']), num_qa) >= min(len(parsed['pairs']), num_qa):
                parsed = retry
        except Exception as e:
            print(f'  Q&A correction call failed ({e}); keeping the first answer.')
    if len(parsed['pairs']) > num_qa:
        print(f"  Trimming {len(parsed['pairs'])} -> {num_qa} pairs.")
        parsed['pairs'] = parsed['pairs'][:num_qa]
    if len(parsed['pairs']) < num_qa:
        print(f"  Warning: only {len(parsed['pairs'])} pair(s) recovered (requested {num_qa}).")
    return parsed

