def encode_image_base64(image_path: str) -> str:
    with open(image_path, 'rb') as f:
        return base64.b64encode(f.read()).decode('utf-8')

def _normalize_images(image_input) -> list:
    """Accepts a path, a list of paths, or a list of (label, path) tuples.
    Returns a list of (label_or_None, path)."""
    if isinstance(image_input, (str, Path)):
        return [(None, str(image_input))]
    items = []
    for item in image_input:
        if isinstance(item, (tuple, list)):
            items.append((item[0], str(item[1])))
        else:
            items.append((None, str(item)))
    return items

def call_openai_vision(prompt: str, image_path, max_retries: int=5, max_tokens: int=CROP_MAX_TOKENS) -> str:
    """Sends a text prompt + one or more images to Azure OpenAI, with
    retry/backoff on rate-limit errors.
    `image_path` may be a single path, a list of paths, or a list of
    (label, path) tuples; labels are sent as text right before each image."""
    if client is None or MODEL_NAME is None:
        raise RuntimeError('Configure Azure OpenAI credentials before analysis.')
    encoded = [(label, encode_image_base64(path)) for label, path in _normalize_images(image_path)]
    last_error = None
    use_json_mode = True
    for attempt in range(1, max_retries + 1):
        try:
            content = [{'type': 'text', 'text': prompt}]
            for label, b64_image in encoded:
                if label:
                    content.append({'type': 'text', 'text': label})
                content.append({'type': 'image_url', 'image_url': {'url': f'data:image/png;base64,{b64_image}', 'detail': 'high'}})
            request = dict(model=MODEL_NAME, messages=[{'role': 'user', 'content': content}], max_tokens=max_tokens)
            if use_json_mode:
                request['response_format'] = {'type': 'json_object'}
            response = client.chat.completions.create(**request)
            if response.choices[0].finish_reason == 'length':
                print('  Warning: response hit the max_tokens limit and may be truncated.')
            return response.choices[0].message.content.strip()
        except Exception as e:
            last_error = e
            error_text = str(e)
            if use_json_mode and ('response_format' in error_text.lower() or 'json_object' in error_text.lower()):
                print('  JSON response mode is unavailable for this Azure deployment; retrying with prompt-enforced JSON.')
                use_json_mode = False
                continue
            if '429' in error_text or 'rate limit' in error_text.lower() or 'RateLimitError' in error_text:
                print(f'  Rate limit hit (attempt {attempt}/{max_retries}). Waiting 15s...')
                time.sleep(15)
            else:
                print(f'  Azure OpenAI call failed (attempt {attempt}/{max_retries}): {error_text[:200]}')
                time.sleep(3)
    raise RuntimeError(f'Azure OpenAI call failed after {max_retries} attempts: {last_error}')

def _call_analysis_json(prompt: str, image_path, max_retries: int=3, max_tokens: int=CROP_MAX_TOKENS) -> dict:
    """Generic: call vision, strip fences, parse JSON. Returns {} on failure."""
    for attempt in range(1, max_retries + 1):
        try:
            raw_text = call_openai_vision(prompt, image_path, max_tokens=max_tokens)
            cleaned = re.sub('^```(?:json)?\\s*|\\s*```$', '', raw_text, flags=re.MULTILINE).strip()
            parsed = json.loads(cleaned)
            if isinstance(parsed, dict):
                return parsed
        except json.JSONDecodeError as e:
            print(f'  Attempt {attempt}/{max_retries}: JSON parse error: {e}')
            max_tokens = min(max_tokens * 2, 16000)
        except Exception as e:
            print(f'  Attempt {attempt}/{max_retries}: call failed: {e}')
        time.sleep(2)
    return {}

