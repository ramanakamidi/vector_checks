def _remove_empty(value):
    """Recursively remove nulls, blank strings, empty lists, and empty objects."""
    if isinstance(value, dict):
        cleaned = {}
        for key, item in value.items():
            compact = _remove_empty(item)
            if compact is not None and compact != '' and (compact != []) and (compact != {}):
                cleaned[key] = compact
        return cleaned
    if isinstance(value, list):
        cleaned = [_remove_empty(item) for item in value]
        return [item for item in cleaned if item is not None and item != '' and (item != []) and (item != {})]
    if isinstance(value, str):
        return value.strip() or None
    return value

